// Generates docs/research/components/product-carousels.spec.md straight from the raw
// browser capture, so no string passes through a hand-written markdown table where an
// invisible character (U+00A0, U+FF5C, U+2019, U+2122) could be normalised away.
//
// Strings are emitted as explicit \uXXXX escapes wherever they contain a non-ASCII
// character, so the spec is unambiguous even if an editor rewrites the file.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const RAW = 'docs/research/www.ankernordics.com/raw/';
const data = JSON.parse(readFileSync(RAW + 'sections-9-30.json', 'utf8'));
const map = JSON.parse(readFileSync('docs/research/www.ankernordics.com/asset-map.json', 'utf8'));

const byBase = {};
for (const [k, v] of Object.entries(map)) byBase[k.split('/').pop().split('?')[0]] = v;
const keys = Object.keys(byBase);

function localPath(file) {
  if (!file) return null;
  const base = file.split('/').pop();
  if (byBase[base]) return byBase[base];
  const stem = base.replace(/_\d{3,4}x(?=\.)/, '').replace(/\.[a-z]+$/i, '');
  const hit = keys.find((k) => k.startsWith(stem.slice(0, 30)));
  return hit ? byBase[hit] : null;
}

/** Show non-ASCII as \uXXXX so the spec survives any editor. */
const esc = (s) =>
  s.replace(/[^\x20-\x7E]/g, (c) => '\\u' + c.codePointAt(0).toString(16).toUpperCase().padStart(4, '0'));

const SECTIONS = [
  ['s10', "What's New", 'WhatsNewCarousel', 9],
  ['s18', 'Anker', 'AnkerProductCarousel', 14],
  ['s24', 'eufy', 'EufyProductCarousel', 20],
  ['s30', 'soundcore', 'SoundcoreProductCarousel', 26],
];

let out = `# Product Carousels Specification

Generated by \`scripts/gen-carousel-spec.mjs\` directly from the raw browser capture — no string
was retyped, so invisible characters survive. **Any text with a \`\\uXXXX\` escape below contains a
non-ASCII character; reproduce it exactly.**

- **Target file:** \`src/components/ProductCarousel.tsx\` (one component, four instances)
- **Reuses:** the existing \`ProductCard\` from \`src/components/ProductCard.tsx\`
- **Measured at:** viewport 1920 (\`lg-desktop\`)

> Root font-size is 14px. Port site class names verbatim; use arbitrary \`[Npx]\` for measured values.

## Common shape

Each is a horizontally scrolling row of product cards preceded by a \`SectionHeading\`
(already built). Section background \`#F5F5F7\`. Card visual treatment is identical to
\`TodaysBestDeal\` — see \`todays-best-deal.spec.md\` for card internals:
\`#EAEAEC\` background, \`rounded-[14px]\`, badge pills with an inset 1px outline,
square-cornered \`#080A0F\` "Shop Now" button.

**Do not re-derive discount percentages from the price pair** — only the strings listed here.

`;

for (const [key, heading, comp, topo] of SECTIONS) {
  const s = data[key];
  if (!s) {
    out += `\n## ${comp} — MISSING from capture\n\n`;
    continue;
  }
  out += `\n---\n\n## ${comp} (topology #${topo}) — heading \`${heading}\`\n\n`;
  out += `Section height **${s.h}px** @1920. ${s.slides} slides, ${s.imgs} images.\n\n`;
  out += `| # | Title | Subtitle | Pills | Price | Was | Image | href |\n|---|---|---|---|---|---|---|---|\n`;
  let missing = 0;
  s.cards.forEach((c, i) => {
    const lp = localPath(c.img);
    if (!lp) missing++;
    const cell = (v) => (v ? '`' + esc(String(v)).replace(/\|/g, '\\|') + '`' : '—');
    out += `| ${i + 1} | ${cell(c.h3)} | ${cell(c.h4)} | ${c.pills.length ? c.pills.map((p) => '`' + esc(p) + '`').join(' ') : '—'} | ${cell(c.now)} | ${cell(c.was)} | ${cell(lp || 'MISSING:' + c.img)} | ${cell(c.href)} |\n`;
  });
  if (missing) out += `\n> **${missing} image(s) not found locally** — resolve before building.\n`;
}

out += `
---

## Implementation notes

- **One component**, four data arrays. Do not write four components.
- Reuse \`ProductCard\`; if its \`Product\` type needs an optional \`subtitle\` for the
  What's New cards (which carry an \`h4\`), add it as optional so existing usage is unaffected.
- No new dependencies — CSS \`overflow-x-auto\` with scroll snap and hidden scrollbar.
- \`"use client"\` only if you add scroll-state; prefer CSS-only.

## Verification

\`npx tsc --noEmit\` must exit 0. Confirm every \`/images/...\` path exists under \`public/\`,
and that any \`\\uXXXX\` string was reproduced with the right code point.
`;

writeFileSync('docs/research/components/product-carousels.spec.md', out);

const all = SECTIONS.flatMap(([k]) => (data[k]?.cards ?? []));
const paths = all.map((c) => localPath(c.img)).filter(Boolean);
